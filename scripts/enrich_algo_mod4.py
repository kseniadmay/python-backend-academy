import heapq

# 1. BFS: поиск кратчайшего пути (по числу пересадок) в невзвешенном графе за O(V + E)
def shortest_path_bfs(graph: dict[str, list[str]], start: str, goal: str) -> list[str] | None:
    if start == goal:
        return [start]
    visited: set[str] = {start}
    queue: deque[tuple[str, list[str]]] = deque([(start, [start])])
    while queue:
        vertex, path = queue.popleft()
        for neighbor in graph.get(vertex, []):
            if neighbor not in visited:
                new_path = path + [neighbor]
                if neighbor == goal:
                    return new_path
                visited.add(neighbor)  # помечаем СРАЗУ при добавлении в очередь!
                queue.append((neighbor, new_path))
    return None

# 2. DFS: подсчёт числа компонент связности за O(V + E)
def count_connected_components(graph: dict[str, list[str]]) -> int:
    visited: set[str] = set()
    components = 0

    def dfs(u: str) -> None:
        visited.add(u)
        for v in graph.get(u, []):
            if v not in visited:
                dfs(v)

    for node in graph:
        if node not in visited:
            components += 1
            dfs(node)
    return components

# 3. Алгоритм Дейкстры: кратчайшие расстояния во взвешенном графе (веса >= 0) через Min-Heap
def dijkstra(weighted_graph: dict[str, list[tuple[str, int]]], start: str) -> dict[str, int]:
    distances: dict[str, int] = {node: float("inf") for node in weighted_graph}  # type: ignore[misc]
    distances[start] = 0
    pq: list[tuple[int, str]] = [(0, start)]  # (текущее_расстояние, вершина)

    while pq:
        cur_dist, u = heapq.heappop(pq)
        if cur_dist > distances[u]:
            continue  # пропускаем устаревшую запись в куче
        for v, weight in weighted_graph[u]:
            new_dist = cur_dist + weight
            if new_dist < distances[v]:
                distances[v] = new_dist
                heapq.heappush(pq, (new_dist, v))
    return distances

