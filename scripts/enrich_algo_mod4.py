def build_csv_row(items: list[int]) -> str:
    """Сборка строки через list + ''.join() за линейное время O(n)."""
    parts: list[str] = []
    for item in items:
        parts.append(str(item * 10))
    return ",".join(parts)

def fast_unordered_remove(arr: list[str], index: int) -> str:
    """
    Трюк Swap-and-Pop: если порядок элементов в массиве НЕ важен,
    удаление по индексу можно выполнить за O(1) вместо O(n)!
    """
    removed = arr[index]
    arr[index] = arr[-1]  # записываем последний элемент на место удаляемого за O(1)
    arr.pop()             # отрезаем хвост за O(1) без сдвига массива
    return removed

print("CSV строка:", build_csv_row([1, 2, 3, 4, 5]))
servers = ["srv-1", "srv-2", "srv-3", "srv-4"]
deleted = fast_unordered_remove(servers, 1)
print(f"Удалён за O(1): {deleted}, оставшиеся серверы: {servers}")
