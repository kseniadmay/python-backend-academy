# 1. Классическая очередь FIFO на базе deque + кольцевой буфер истории (maxlen=3)
task_queue: deque[str] = deque(["task_1", "task_2"])
task_queue.append("task_3")          # в конец очереди за O(1)
first_done = task_queue.popleft()    # из начала очереди за O(1)

recent_logs: deque[str] = deque(maxlen=3)
