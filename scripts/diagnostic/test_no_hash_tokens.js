let marked;
try {
  marked = require('marked');
} catch (e) {
  console.log('[SKIP] Optional module "marked" not installed. Scratch test skipped.');
  process.exit(0);
}


const md = `
**Почему выбор структуры данных важен**

Программа идеально работает с десятью элементами – и зависает на десяти тысячах. Причина почти всегда не в железе, а в неправильном выборе структуры данных.

**List: когда важен порядок**

Список – динамический массив. Идеален, когда нужно сохранить порядок элементов и обращаться к ним по индексу.

- **Быстрые операции – O(1):** \`arr.append(x)\`, \`arr.pop()\`. Они не требуют прохода по всему массиву.
- **Медленные операции – O(n):** \`arr.insert(0, x)\`, \`arr.pop(0)\`. Все они требуют сдвига элементов.

Почему \`insert(0, x)\` медленный? Python не может просто «втиснуть» элемент в начало.

\`[1, 2, 3, 4, 5] → insert(0, 0) → [0, 1, 2, 3, 4, 5]\`

Сортировка \`sorted(arr)\` стоит особняком – это O(n log n).

**Dict: мгновенный поиск по ключу**

Словарь – структура «ключ – значение» на основе хэш-таблицы.
`;

const tokens = marked.lexer(md);
console.log("Tokens count:", tokens.length);
tokens.forEach(t => {
    console.log(t.type, t.depth || '', JSON.stringify((t.text || '').slice(0, 50)));
});
