class DomainError(Exception):
    pass

class InsufficientFundsError(DomainError):
    pass

@dataclass
class Wallet:
    user_id: int
    balance: int

# --- 1. Слой доступа к данным (Data Access Layer / Repository) ---
class WalletRepository:
    def __init__(self) -> None:
        self._storage: dict[int, Wallet] = {1: Wallet(user_id=1, balance=1000)}

    def get(self, user_id: int) -> Wallet:
        return self._storage[user_id]

    def save(self, wallet: Wallet) -> None:
        self._storage[wallet.user_id] = wallet

# --- 2. Сервисный слой бизнес-логики (Business Layer / Service) ---
